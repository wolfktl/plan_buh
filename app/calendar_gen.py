"""Генерация налогового календаря РФ на 2026 год.

Даты рассчитываются с автоматическим переносом срока на ближайший рабочий
день (п. 7 ст. 6.1 НК РФ) по производственному календарю 2026
(Постановление Правительства РФ № 1466 от 24.09.2025 + ст. 112 ТК РФ).

Каждое событие помечено полем ``applies`` — набором условий применимости,
по которым фронтенд/бэкенд решает, показывать ли его конкретному контрагенту:
  osno       — общая система (НДС, налог на прибыль)
  usn        — упрощёнка
  employees  — есть сотрудники (НДФЛ, взносы, персучёт)
  ip         — индивидуальный предприниматель (взносы за себя, 3-НДФЛ)
  all        — всем
"""
from datetime import date, timedelta

# Нерабочие праздничные/перенесённые будни. Сб и Вс определяются автоматически.
HOLIDAYS = {
    "2026-01-01", "2026-01-02", "2026-01-05", "2026-01-06", "2026-01-07",
    "2026-01-08", "2026-01-09",
    "2026-02-23",
    "2026-03-09",            # перенос с 8 марта (вс)
    "2026-05-01", "2026-05-11",  # 1 мая; 11 мая — перенос с 9 мая (сб)
    "2026-06-12",
    "2026-11-04",
    "2026-12-31",            # перенос с 4 января
    # Ориентир для годовой отчётности за 2026 (начало 2027)
    "2027-01-01", "2027-01-02", "2027-01-03", "2027-01-04",
    "2027-01-05", "2027-01-06", "2027-01-07", "2027-01-08",
}

MONTHS_GEN = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля",
              "августа", "сентября", "октября", "ноября", "декабря"]
LAST_DAY = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
VZNOS_NOTICE_MONTHS = {1, 2, 4, 5, 7, 8, 10, 11}  # 1-й и 2-й месяцы кварталов


def _is_non_working(d: date) -> bool:
    if d.weekday() >= 5:  # 5=сб, 6=вс
        return True
    return d.isoformat() in HOLIDAYS


def adjust(y: int, m: int, d: int) -> tuple[date, bool]:
    """Вернуть (дата с переносом, был_ли_перенос). m — 0-индекс."""
    cur = date(y, m + 1, d)
    moved = False
    while _is_non_working(cur):
        cur += timedelta(days=1)
        moved = True
    return cur, moved


def build_events(year: int = 2026) -> list[dict]:
    events: list[dict] = []
    counter = {"n": 0}

    def add(y, m, d, title, cat, type_, applies, note=""):
        dt, moved = adjust(y, m, d)
        counter["n"] += 1
        events.append({
            "key": f"b{counter['n']}",
            "date": dt.isoformat(),
            "title": title,
            "cat": cat,
            "type": type_,          # pay | rep | not
            "applies": applies,
            "note": note,
            "moved": moved,
        })

    Y = year

    # ---- Ежемесячные события ----
    for m in range(12):
        prev_m = (m + 11) % 12
        prev = MONTHS_GEN[prev_m]
        cur = MONTHS_GEN[m]

        if m != 0:
            add(Y, m, 3,
                f"Уведомление по НДФЛ (за 23–{LAST_DAY[prev_m]} {prev})",
                "ndfl", "not", ["employees"],
                f"НДФЛ, удержанный с 23-го по последнее число {prev}")
            add(Y, m, 5,
                f"Уплата НДФЛ (за 23–конец {prev})",
                "ndfl", "pay", ["employees"],
                f"Перечисление налога за второй период {prev}")

        add(Y, m, 25,
            f"Уведомление по НДФЛ (за 1–22 {cur})",
            "ndfl", "not", ["employees"],
            f"НДФЛ, удержанный с 1-го по 22-е число {cur}")
        add(Y, m, 25,
            f"Персонифицированные сведения о физлицах (за {prev})",
            "otchet", "rep", ["employees"],
            "Ежемесячно в СФР за предыдущий месяц")
        if m in VZNOS_NOTICE_MONTHS:
            add(Y, m, 25,
                f"Уведомление по страховым взносам (за {prev})",
                "vznos", "not", ["employees"],
                "В 3-й месяц квартала заменяется РСВ")
        add(Y, m, 28,
            "Уплата ЕНП — единый налоговый платёж",
            "vznos", "pay", ["all"],
            f"НДФЛ (1–22 {cur}), взносы за {prev}, авансы по налогам")

    # ---- Квартальная отчётность (25-е месяца после квартала) ----
    q_month = [3, 6, 9]          # апрель, июль, октябрь
    q_label = ["I квартал", "полугодие", "9 месяцев"]
    q_rim = ["I", "II", "III"]
    for q in range(3):
        qm, lbl = q_month[q], q_label[q]
        add(Y, qm, 25, f"Декларация по НДС ({q_rim[q]} квартал)",
            "nds", "rep", ["osno"],
            "Уплата — тремя равными частями до 28-го числа каждого из 3 следующих месяцев")
        add(Y, qm, 25, f"РСВ — расчёт по страховым взносам ({lbl})",
            "vznos", "rep", ["employees"], "Все работодатели")
        add(Y, qm, 25, f"6-НДФЛ ({lbl})", "ndfl", "rep", ["employees"],
            "Расчёт сумм НДФЛ")
        add(Y, qm, 25, f"Декларация по налогу на прибыль ({lbl})",
            "pribyl", "rep", ["osno"], "При ежеквартальной уплате авансов")
        add(Y, qm, 25, f"ЕФС-1, раздел 2 — взносы на травматизм ({lbl})",
            "vznos", "rep", ["employees"], "В СФР ежеквартально")
        add(Y, qm, 25, f"Уведомление по авансу УСН ({lbl})",
            "usn", "not", ["usn"], "Аванс по УСН за квартал")
        add(Y, qm, 28, f"Уплата аванса по УСН ({lbl})",
            "usn", "pay", ["usn"], "Авансовый платёж по УСН")

    # ---- Годовая отчётность за 2025 (сдаётся в 2026) ----
    add(Y, 0, 26, "Декларация по НДС за IV квартал 2025", "nds", "rep", ["osno"],
        "Годовое закрытие НДС (срок 25.01 — выходной)")
    add(Y, 0, 26, "РСВ за 2025 год", "vznos", "rep", ["employees"], "Годовой расчёт")
    add(Y, 0, 26, "Персонифицированные сведения за декабрь 2025", "otchet", "rep",
        ["employees"], "В СФР")
    add(Y, 0, 26, "ЕФС-1, раздел 2 за 2025 (травматизм)", "vznos", "rep",
        ["employees"], "Годовой")
    add(Y, 0, 25, "ЕФС-1, подраздел 1.2 (стаж) за 2025", "otchet", "rep",
        ["employees"], "Сведения о стаже — ежегодно в СФР")
    add(Y, 1, 25, "6-НДФЛ за 2025 год", "ndfl", "rep", ["employees"],
        "Годовой расчёт со справками о доходах")
    add(Y, 2, 25, "Декларация по налогу на прибыль за 2025", "pribyl", "rep",
        ["osno"], "Годовая декларация")
    add(Y, 2, 25, "Декларация по УСН за 2025 — организации", "usn", "rep", ["usn"],
        "Для ООО на УСН")
    add(Y, 2, 31, "Бухгалтерская (финансовая) отчётность за 2025", "otchet", "rep",
        ["all"], "Баланс и приложения — в ФНС и ГИРБО")
    add(Y, 2, 30, "Подтверждение основного вида деятельности в СФР", "otchet", "rep",
        ["employees"], "Для тарифа взносов на травматизм")
    add(Y, 3, 27, "Декларация по УСН за 2025 — ИП", "usn", "rep", ["usn", "ip"],
        "Для ИП на УСН (срок 25.04 — выходной)")
    add(Y, 3, 30, "Декларация 3-НДФЛ за 2025", "ipself", "rep", ["ip"],
        "ИП на ОСНО и физлица, декларирующие доходы")

    # ---- Платежи по итогам года и взносы ИП ----
    add(Y, 2, 30, "Уплата УСН за 2025 — организации", "usn", "pay", ["usn"],
        "Годовой налог по УСН (срок 28.03 — выходной)")
    add(Y, 3, 28, "Уплата УСН за 2025 — ИП", "usn", "pay", ["usn", "ip"],
        "Годовой налог по УСН для ИП")
    add(Y, 3, 28, "Уплата налога на прибыль за 2025", "pribyl", "pay", ["osno"],
        "Годовой налог")
    add(Y, 6, 1, "Взносы ИП за себя: 1% с дохода свыше 300 000 ₽ за 2025",
        "ipself", "pay", ["ip"], "Срок — 1 июля")
    add(Y, 6, 15, "Уплата НДФЛ по 3-НДФЛ за 2025 (ИП на ОСНО)", "ipself", "pay",
        ["ip"], "Итоговый НДФЛ предпринимателя")
    add(Y, 11, 28, "Фиксированные взносы ИП за себя за 2026", "ipself", "pay",
        ["ip"], "Срок — 28 декабря; сумму уточняйте на текущий год")

    # ---- Начало 2027: годовое закрытие 2026 (ориентиры) ----
    add(2027, 0, 25, "Декларация по НДС за IV квартал 2026", "nds", "rep", ["osno"],
        "Годовое закрытие НДС за 2026")
    add(2027, 0, 25, "РСВ за 2026 год", "vznos", "rep", ["employees"], "Годовой расчёт")
    add(2027, 0, 25, "6-НДФЛ за 2026 год", "ndfl", "rep", ["employees"], "Годовой расчёт")

    events.sort(key=lambda e: (e["date"], e["type"]))
    return events


def applies_to(event: dict, form: str, tax_system: str, has_employees: bool) -> bool:
    """Применимо ли событие контрагенту с данным профилем."""
    a = event["applies"]
    if "all" in a:
        return True
    ok = False
    if "osno" in a and tax_system == "osno":
        ok = True
    if "usn" in a and tax_system == "usn":
        ok = True
    if "employees" in a and has_employees:
        ok = True
    if "ip" in a and form == "ip":
        ok = True
    return ok


# Кэшируем — календарь статичен в пределах года.
_CACHE: dict[int, list[dict]] = {}


def get_events(year: int = 2026) -> list[dict]:
    if year not in _CACHE:
        _CACHE[year] = build_events(year)
    return _CACHE[year]
